package file

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

// Core alone knows no ecosystem: only the conventions that hold in every
// language decide a file, and a pack's own are not guessed at.
func TestClassifier_WithNoConventions(t *testing.T) {
	c := NewClassifier()
	assert.Equal(t, RoleTest, c.Role("tests/OrderTest.php", false, false, ""))
	assert.Equal(t, RoleTest, c.Role("features/checkout.feature", false, false, ""))
	assert.Equal(t, RoleNonCode, c.Role("client/src/style.css", false, false, ""))
	assert.Equal(t, RoleProduction, c.Role("app/src/androidTest/java/com/acme/Ui.kt", false, false, ""))
	assert.Equal(t, RoleProduction, c.Role("client/src/__tests__/nav.ts", false, false, ""))
	assert.True(t, c.IsThirdParty("vendor/github.com/pkg/errors/errors.go", nil))
	assert.False(t, c.IsThirdParty("node_modules/react/index.js", nil))
	assert.True(t, c.IsGenerated([]byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n")))
	assert.False(t, c.IsGenerated([]byte("# Generated by Django 3.2.4 on 2021-06-11 09:00\n")))
	assert.Equal(t, "", c.SystemKind("Dockerfile", nil))
}

// A lockfile is text that is not code, whatever its extension.
func TestClassifier_LockfileIsNonCode(t *testing.T) {
	c := NewClassifier()
	assert.Equal(t, RoleNonCode, c.Role("go.sum", false, false, SystemKindLockfile))
	assert.Equal(t, RoleProduction, c.Role("go.sum", false, false, ""))
}

// Registered conventions answer in registration order, once per name.
func TestClassifier_Conventions(t *testing.T) {
	c := NewClassifier(
		Conventions{Name: "a", SystemKind: func(string, []byte) string { return SystemKindBuild }, IsTest: func(p string) bool { return p == "x/a_check.z" }},
		Conventions{Name: "b", SystemKind: func(string, []byte) string { return SystemKindCI }, ThirdPartyDirs: []string{"deps/"}, PackageDirExts: []string{".z"}},
		Conventions{Name: "a", SystemKind: func(string, []byte) string { return SystemKindDeploy }},
	)
	assert.Equal(t, SystemKindBuild, c.SystemKind("anything", nil))
	assert.True(t, c.IsTestPath("./x/a_check.z"))
	assert.True(t, c.IsThirdParty("deps/lib/a.y", nil))
	assert.False(t, c.IsThirdParty("src/org/deps/a.z", nil), "a directory inside a package-directory language's source root is a package")
	class := c.Classify("deps/lib/a.y", nil)
	assert.True(t, class.ThirdParty)
	assert.Equal(t, "", class.SystemKind, "someone else's code describes nothing of this project's")
}
